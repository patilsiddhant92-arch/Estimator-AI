# T-009 (ruling 22): the proposal prints one demolition exclusion. These jobs have no Demolition Scope block, so the
# general line stays and the template's specific line is gone; everything else is as sent.
SPECIFIC_DEMOLITION = "Any demolition work not specifically mentioned"


def _one_demolition_line(texts):
    return [t for t in texts if t != SPECIFIC_DEMOLITION]

INTERNAL_MARKERS = ("🟡", "🔴", "🟠", "🟢", "PRICE PENDING", "PRICE NEEDS REVIEW", "[CONFIRMED", "ASSUMPTION]",
                    "Estimation Assistant", "Estimator AI", "generated by")


def _written(small_job, proposal_template, tmp_path):
    out = write_proposal(small_job, proposal_template, tmp_path / "p.docx")
    return out, docx.Document(str(out))


def _paragraph(document, text):
    return next(p for p in document.paragraphs if squash(p.text) == text)


def _mark_rPr(paragraph):
    pPr = paragraph._p.pPr
    return pPr.find(qn("w:rPr")) if pPr is not None else None


def _is_small_gap(paragraph):
    """An empty paragraph whose paragraph mark is sized 12 half-points (6pt) — the
    small blank line the sent proposal puts before every front-end note."""
    if paragraph.text.strip():
        return False
    rPr = _mark_rPr(paragraph)
    sz = rPr.find(qn("w:sz")) if rPr is not None else None
    return sz is not None and sz.get(qn("w:val")) == "12"


def test_block_headers(small_job, proposal_template, tmp_path):
    _, document = _written(small_job, proposal_template, tmp_path)
    header = _paragraph(document, "Qty (2) Exhaust Fan EF-1, 2")
    assert header.style.name == "PR2" and WordLists.written_numbering(header) is None
    assert header.paragraph_format.left_indent == Twips(1566)
    assert all(r.bold for r in header.runs) and header.runs[0].font.size == Pt(12)


def test_block_header_paragraph_mark_is_bold_and_sized(small_job, proposal_template, tmp_path):
    """Word draws the "1." number from the paragraph mark, not the run text — the
    mark itself must be bold 12pt, or the number comes out small and plain."""
    _, document = _written(small_job, proposal_template, tmp_path)
    header = _paragraph(document, "Qty (2) Exhaust Fan EF-1, 2")
    rPr = _mark_rPr(header)
    assert rPr is not None and rPr.find(qn("w:b")) is not None
    sz = rPr.find(qn("w:sz"))
    assert sz is not None and sz.get(qn("w:val")) == "24"


def test_lines_and_notes(small_job, proposal_template, tmp_path):
    _, document = _written(small_job, proposal_template, tmp_path)
    assert WordLists.written_numbering(_paragraph(document, "Furnish and Install DDC Controller")) == (12, 4)
    assert WordLists.written_numbering(_paragraph(document, "Mfr. to Provide Relay")) == (12, 5)
    note = _paragraph(document, "*DAMPERS BY OTHERS")
    assert WordLists.written_numbering(note) is None and note.paragraph_format.left_indent == Twips(1440)


def test_block_lines_notes_and_headers_are_calibri(small_job, proposal_template, tmp_path):
    """Word measures every equipment-block word in the team's sent proposals as Calibri,
    while the template's Normal style (used by block lines and notes) is Myriad Pro — so
    each run is forced to Calibri explicitly rather than left to fall back to the style."""
    _, document = _written(small_job, proposal_template, tmp_path)
    line = _paragraph(document, "Furnish and Install DDC Controller")
    note = _paragraph(document, "*DAMPERS BY OTHERS")
    header = _paragraph(document, "Qty (2) Exhaust Fan EF-1, 2")
    for paragraph in (line, note, header):
        assert paragraph.runs and all(run.font.name == "Calibri" for run in paragraph.runs)


